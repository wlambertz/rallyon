func executeLegacySpec(args ...string) (string, string, error) {
	root := &cobra.Command{Use: "ro", SilenceErrors: true, SilenceUsage: true}
	registerSpecCommands(root)
	var stdout, stderr bytes.Buffer
	root.SetOut(&stdout)
	root.SetErr(&stderr)
	root.SetArgs(args)
	err := root.Execute()
	return stdout.String(), stderr.String(), err
}

func legacySpecFixture(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	t.Setenv("RO_PATHS_SERVICEROOT", dir)
	t.Setenv("RO_SPECS_DIRECTORY", dir)
	t.Setenv("RO_SPECS_DEFAULTTEMPLATE", "basic")
	t.Setenv("RO_SPECS_SCHEMAURL", "")
	return dir
}

func requireLegacyWarning(t *testing.T, stderr string) {
	t.Helper()
	if stderr != legacySpecWarning+"\n" {
		t.Fatalf("stderr = %q, want exactly one common deprecation warning", stderr)
	}
}

func TestLegacySpecRoutes(t *testing.T) {
	for _, prefix := range [][]string{nil, {"spec"}} {
		t.Run(strings.Join(append(prefix, "commands"), "-"), func(t *testing.T) {
			dir := legacySpecFixture(t)
			path := filepath.Join(dir, "feature.yaml")
			run := func(leaf string, args ...string) string {
				t.Helper()
				argv := append(append([]string{}, prefix...), leaf)
				stdout, stderr, err := executeLegacySpec(append(argv, args...)...)
				if err != nil {
					t.Fatalf("%v: %v", argv, err)
				}
				requireLegacyWarning(t, stderr)
				return stdout
			}
			for _, schema := range []string{"", "https://example.test/legacy-schema.json"} {
				t.Setenv("RO_SPECS_SCHEMAURL", schema)
				want := fmt.Sprintf("OpenSpec spec created: %s\nTemplate used: basic\n", path)
				if schema != "" {
					want += "Schema: " + schema + "\n"
				}
				if got := run("create", "feature"); got != want {
					t.Fatalf("create stdout = %q, want %q", got, want)
				}
			}
			content, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Contains(content, []byte("specification: \"feature\"")) || !bytes.Contains(content, []byte("# Generated by ro spec create")) {
				t.Fatalf("unexpected generated content: %s", content)
			}
			if got := run("validate", path); got != "Spec validation PASSED: "+path+"\n" {
				t.Fatalf("validate stdout = %q", got)
			}
			for _, format := range []string{"yaml", "json", "toon"} {
				file := filepath.Join(dir, "raw."+format)
				data := "raw " + format + " content\n"
				if err := os.WriteFile(file, []byte(data), 0600); err != nil {
					t.Fatal(err)
				}
				want := "OpenSpec Specification: " + file + "\n========================\n\n" + data + "\n"
				if got := run("view", file); got != want {
					t.Fatalf("view stdout = %q, want %q", got, want)
				}
			}
		})
	}
}

func TestLegacySpecErrors(t *testing.T) {
	for _, prefix := range [][]string{nil, {"spec"}} {
		t.Run(strings.Join(append(prefix, "errors"), "-"), func(t *testing.T) {
			dir := legacySpecFixture(t)
			malformed := filepath.Join(dir, "malformed.yaml")
			invalid := filepath.Join(dir, "invalid.yaml")
			for path, data := range map[string]string{malformed: "ticket: [", invalid: "specification: invalid\n"} {
				if err := os.WriteFile(path, []byte(data), 0600); err != nil {
					t.Fatal(err)
				}
			}
			for _, tc := range []struct {
				args            []string
				message, stdout string
			}{
				{[]string{"create"}, "accepts 1 arg(s), received 0", ""},
				{[]string{"validate"}, "accepts 1 arg(s), received 0", ""},
				{[]string{"view"}, "accepts 1 arg(s), received 0", ""},
				{[]string{"create", "a", "b"}, "accepts 1 arg(s), received 2", ""},
				{[]string{"validate", "a", "b"}, "accepts 1 arg(s), received 2", ""},
				{[]string{"view", "a", "b"}, "accepts 1 arg(s), received 2", ""},
				{[]string{"create", "missing/feature"}, "failed to write spec file:", ""},
				{[]string{"validate", filepath.Join(dir, "missing")}, "failed to read spec file:", ""},
				{[]string{"view", filepath.Join(dir, "missing")}, "failed to read spec file:", ""},
				{[]string{"validate", malformed}, "failed to parse spec YAML:", ""},
				{[]string{"validate", invalid}, "spec validation failed - see errors above", "Spec validation FAILED for: " + invalid + "\n  - missing 'title' field\n  - missing 'status' field\n  - missing 'epic' field\n  - missing 'ticket' section\n  - missing 'filesToBeCreated' field\n  - missing 'codeReferences' field\n"},
				{[]string{"create", "--template", "basic", "feature"}, "unknown flag: --template", ""},
			} {
				t.Run(strings.Join(tc.args, " "), func(t *testing.T) {
					stdout, stderr, err := executeLegacySpec(append(append([]string{}, prefix...), tc.args...)...)
					if err == nil || !strings.Contains(err.Error(), tc.message) {
						t.Fatalf("error = %v, want %q", err, tc.message)
					}
					requireLegacyWarning(t, stderr)
					if stdout != tc.stdout {
						t.Fatalf("stdout = %q, want %q", stdout, tc.stdout)
					}
				})
			}
			t.Setenv("RO_PATHS_SERVICEROOT", filepath.Join(dir, "missing-service"))
			stdout, stderr, err := executeLegacySpec(append(append([]string{}, prefix...), "create", "feature")...)
			if err == nil || !strings.Contains(err.Error(), "config error: paths.serviceRoot does not exist:") {
				t.Fatalf("error = %v", err)
			}
			requireLegacyWarning(t, stderr)
			if stdout != "" {
				t.Fatalf("stdout = %q", stdout)
			}
		})
	}
}

func TestLegacySpecHelpAndRegistration(t *testing.T) {
	for _, prefix := range [][]string{nil, {"spec"}} {
		for _, leaf := range []string{"create", "validate", "view"} {
			args := append(append([]string{}, prefix...), leaf, "--help")
			stdout, stderr, err := executeLegacySpec(args...)
			if err != nil {
				t.Fatal(err)
			}
			if strings.Count(stdout, legacySpecWarning) != 1 || stderr != "" {
				t.Fatalf("help stdout=%q stderr=%q", stdout, stderr)
			}
		}
	}
	for _, args := range [][]string{{"--help"}, {"spec", "--help"}} {
		stdout, _, err := executeLegacySpec(args...)
		if err != nil {
			t.Fatal(err)
		}
		for _, leaf := range []string{"create", "validate", "view"} {
			if !strings.Contains(stdout, leaf) {
				t.Fatalf("%v help missing %s", args, leaf)
			}
		}
	}
	for _, path := range [][]string{{"create"}, {"validate"}, {"view"}, {"spec", "create"}, {"spec", "validate"}, {"spec", "view"}} {
		leaf, _, err := rootCmd.Find(path)
		if err != nil || leaf.CommandPath() != "ro "+strings.Join(path, " ") || leaf.Deprecated != "" || leaf.Hidden {
			t.Fatalf("route %v: leaf=%v err=%v", path, leaf, err)
		}
	}
}

func TestLegacySchemaURLConfig(t *testing.T) {
	dir := legacySpecFixture(t)
	if err := os.WriteFile(filepath.Join(dir, "ro.yaml"), []byte("specs:\n  schemaURL: https://example.test/custom.json\n"), 0600); err != nil {
		t.Fatal(err)
	}
	loaded, err := config.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if loaded.Specs.SchemaURL != "https://example.test/custom.json" {
		t.Fatalf("configured schemaURL=%q", loaded.Specs.SchemaURL)
	}
	if err := os.Remove(filepath.Join(dir, "ro.yaml")); err != nil {
		t.Fatal(err)
	}
	loaded, err = config.Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if loaded.Specs.SchemaURL != "" {
		t.Fatalf("default schemaURL=%q", loaded.Specs.SchemaURL)
	}
}
