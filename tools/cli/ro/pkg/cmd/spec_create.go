package cmd

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"
	"github.com/wlambertz/rallyon/tools/cli/ro/pkg/config"
)

// specCreateCmd represents the create command for OpenSpec specs
var specCreateCmd = &cobra.Command{
	Use:   "create [name]",
	Short: "Create a new OpenSpec specification ticket",
	Long: `Create a new OpenSpec specification ticket in YAML, JSON, or TOON format.

The command generates a spec file based on the configured default template
and writes it to the configured specs directory.

Example:
  ro spec create my-feature-auth
  ro spec create --template basic my-feature`,
	Args: cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		name := args[0]
		cfg, err := config.Load("")
		if err != nil {
			return fmt.Errorf("config error: %w", err)
		}

		// Determine output directory
		outputDir := cfg.Specs.Directory
		if outputDir == "" {
			outputDir = "docs/wiki/specs"
		}

		// Determine template
		template := cfg.Specs.DefaultTemplate
		if template == "" {
			template = "basic"
		}

		// Determine schema URL
		schemaURL := cfg.Specs.SchemaURL
		if schemaURL == "" {
			schemaURL = "https://openspec.tech/schema/v1.1/openspec-schema.json"
		}

		// Create spec file content based on template
		var specContent string

		switch template {
		case "basic":
			specContent = basicSpecTemplate(name)
		case "auth":
			specContent = authSpecTemplate(name)
		default:
			specContent = basicSpecTemplate(name)
		}

		// Write to file
		filename := fmt.Sprintf("%s.yaml", name)
		filePath := fmt.Sprintf("%s/%s", outputDir, filename)

		if err := os.WriteFile(filePath, []byte(specContent), 0644); err != nil {
			return fmt.Errorf("failed to write spec file: %w", err)
		}

		fmt.Printf("OpenSpec spec created: %s\n", filePath)
		fmt.Printf("Template used: %s\n", template)
		fmt.Printf("Schema: %s\n", schemaURL)

		return nil
	},
}

func init() {
	rootCmd.AddCommand(specCreateCmd)
}

func basicSpecTemplate(name string) string {
	return fmt.Sprintf(`# OpenSpec Specification: %s
# Generated by ro spec create

specification: "%s"
title: "%s"
status: draft

epic: "%s workflow"

ticket:
  title: "%s"
  description: |
    Description of the %%s feature or requirement.

  acceptanceCriteria:
    - given: "no implementation"
      when: "user interacts with the %s feature"
      then: "expected behavior is shown"

  implementationSteps:
    - text: "Implement the %s feature"
      type: "development"
      references: []
      codeReferences: []
      testSpecification:
        testTypes: ["unit", "integration"]
        qualityGates: ["all acceptance criteria covered"]

  dependencies: []

filesToBeCreated: []
filesToBeModified: []
filesToBeDeleted: []
filesToBeReferenced: []
codeReferences: []
typeReferences: []
`, name, name, name, name, name, name)
}

func authSpecTemplate(name string) string {
	return fmt.Sprintf(`# OpenSpec Specification: %s (Auth-focused)
# Generated by ro spec create

specification: "%s"
title: "%s - Authentication"
status: draft

epic: "%s authentication"

ticket:
  title: "%s"
  description: |
    JWT-based authentication implementation for %%s.

  acceptanceCriteria:
    - given: "no authentication token"
      when: "GET /auth/me endpoint is called"
      then: "401 Unauthorized response"

    - given: "valid JWT token"
      when: "GET /auth/me endpoint is called"
      then: "200 OK with user profile"

  implementationSteps:
    - text: "Add JWT authentication middleware"
      type: "development"
      references: []
      codeReferences: []
      testSpecification:
        testTypes: ["integration"]
        qualityGates: ["auth paths covered", "token validation"]

  dependencies: []

filesToBeCreated: []
filesToBeModified: []
filesToBeDeleted: []
filesToBeReferenced: []
codeReferences: []
typeReferences: []
`, name, name, name, name, name)
}
